// PasteboardSnapshot.swift — VoiceType
//
// Full-fidelity clipboard snapshot/restore for paste-based text insertion.
// Unlike the old approach (save/restore only the .string type), this captures
// every NSPasteboardItem and every type each item carries — images, files,
// RTF, whatever the user had copied — so a dictation paste never destroys it.
//
// docs/plans/reliable-dictation.md § D1.

import AppKit

/// Marks the transient dictation string VoiceType writes to the clipboard so
/// pasteboard managers (Raycast, Maccy, Paste, …) that honor the
/// nspasteboard.org convention skip recording it into their history.
enum TransientPasteboardMarker {
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}

/// Outcome of attempting to snapshot a pasteboard's full contents.
enum PasteboardSnapshotResult: Equatable {
    case captured(PasteboardSnapshot)
    case tooLarge(bytes: Int)
    case timedOut
    case changedDuringCapture
    /// At least one type a pasteboard item advertised (in `NSPasteboardItem.types`)
    /// returned `nil` from `data(forType:)` — the snapshot would be a partial
    /// copy, so it is refused rather than presented as complete. Restoring it
    /// later would silently drop that type's data. `unreadableTypes` holds the
    /// affected types' raw values (deduplicated, in first-seen order) for
    /// logging — never the pasteboard's actual content.
    case incomplete(unreadableTypes: [String])
}

/// A full-fidelity copy of a pasteboard's contents at a point in time,
/// tagged with the `changeCount` it was taken at so callers can detect
/// whether the pasteboard moved on before they restore this snapshot.
struct PasteboardSnapshot: Equatable {
    /// One dictionary per NSPasteboardItem, order preserved.
    let items: [[NSPasteboard.PasteboardType: Data]]
    /// `pasteboard.changeCount` at the moment this snapshot was taken.
    let changeCount: Int

    static let maxTotalBytes = 64 * 1024 * 1024

    var totalBytes: Int {
        items.reduce(0) { sum, item in
            sum + item.values.reduce(0) { $0 + $1.count }
        }
    }

    /// Synchronous capture. Reads every type of every item on `pasteboard`.
    /// Returns `.tooLarge` as soon as the running byte total exceeds
    /// `maxTotalBytes` (large payloads are abandoned early rather than fully
    /// materialized) — checked first, so it can still short-circuit mid-item.
    /// Returns `.changedDuringCapture` if the pasteboard's `changeCount`
    /// moved while reading — checked next, ahead of `.incomplete`. Otherwise,
    /// if any type a pasteboard item advertised returned `nil` data, returns
    /// `.incomplete` naming those types instead of silently presenting a
    /// partial snapshot as complete (an item that ends up with no readable
    /// type at all is simply left out of `items`, same as before).
    static func materialize(
        from pasteboard: NSPasteboard,
        maxTotalBytes: Int = maxTotalBytes
    ) -> PasteboardSnapshotResult {
        let startChangeCount = pasteboard.changeCount
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        var totalBytes = 0
        var unreadableTypes: [String] = []
        var seenUnreadableTypes: Set<String> = []

        for pasteboardItem in pasteboard.pasteboardItems ?? [] {
            var captured: [NSPasteboard.PasteboardType: Data] = [:]
            for type in pasteboardItem.types {
                guard let data = pasteboardItem.data(forType: type) else {
                    if seenUnreadableTypes.insert(type.rawValue).inserted {
                        unreadableTypes.append(type.rawValue)
                    }
                    continue
                }
                captured[type] = data
                totalBytes += data.count
                if totalBytes > maxTotalBytes {
                    return .tooLarge(bytes: totalBytes)
                }
            }
            if !captured.isEmpty {
                items.append(captured)
            }
        }

        guard pasteboard.changeCount == startChangeCount else {
            return .changedDuringCapture
        }

        guard unreadableTypes.isEmpty else {
            return .incomplete(unreadableTypes: unreadableTypes)
        }

        return .captured(PasteboardSnapshot(items: items, changeCount: startChangeCount))
    }

    /// Asynchronous capture off the main thread, through a separate
    /// `NSPasteboard` instance bound to the same name — the background read
    /// never touches the caller's pasteboard object and never writes.
    /// Retries once on `.changedDuringCapture`. Races against `deadline`;
    /// if the deadline wins, `.timedOut` is returned and the (possibly still
    /// running) background read's result is discarded.
    static func capture(
        from pasteboard: NSPasteboard,
        deadline: Duration = .milliseconds(500)
    ) async -> PasteboardSnapshotResult {
        let name = pasteboard.name
        let first = await captureOnce(pasteboardName: name, deadline: deadline)
        guard case .changedDuringCapture = first else {
            return first
        }
        return await captureOnce(pasteboardName: name, deadline: deadline)
    }

    /// Writes this snapshot to `pasteboard`, replacing its current contents.
    /// An empty snapshot (no items) simply clears the pasteboard.
    func write(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }

        let pasteboardItems = items.map { captured -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in captured {
                item.setData(data, forType: type)
            }
            return item
        }
        pasteboard.writeObjects(pasteboardItems)
    }

    // MARK: - Private

    /// Single race between a background `materialize` call (via its own
    /// `NSPasteboard` instance) and `deadline`. The continuation is resumed
    /// exactly once, guarded by a lock, whichever side wins.
    private static func captureOnce(
        pasteboardName: NSPasteboard.Name,
        deadline: Duration
    ) async -> PasteboardSnapshotResult {
        await withCheckedContinuation { (continuation: CheckedContinuation<PasteboardSnapshotResult, Never>) in
            let resumeLock = NSLock()
            var didResume = false

            func resumeOnce(with result: PasteboardSnapshotResult) {
                resumeLock.lock()
                let alreadyResumed = didResume
                didResume = true
                resumeLock.unlock()
                guard !alreadyResumed else { return }
                continuation.resume(returning: result)
            }

            DispatchQueue.global(qos: .userInitiated).async {
                let backgroundPasteboard = NSPasteboard(name: pasteboardName)
                let result = materialize(from: backgroundPasteboard)
                resumeOnce(with: result)
            }

            Task {
                try? await Task.sleep(for: deadline)
                resumeOnce(with: .timedOut)
            }
        }
    }
}
